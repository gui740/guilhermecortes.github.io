_MATRIZES["tronco_vermelho"] = _MATRIZES["tronco"]

NOMES = sorted(_MATRIZES)


def _linhas(nome):
    rows = [r for r in _MATRIZES[nome].strip("\n").split("\n")]
    rows = [(r + "." * 16)[:16] for r in rows]
    rows = (rows + ["." * 16] * 16)[:16]
    return rows


@lru_cache(maxsize=None)
def icone(nome, corrompido=False, invertido=False):
    """Retorna PIL RGBA 16x16."""
    pal = dict(PALETA)
    if nome == "tronco_vermelho":
        pal.update(TRONCO_VERMELHO)
    if corrompido:  # paleta trocada
        chaves = sorted(pal)
        vals = [pal[k] for k in chaves]
        vals = vals[3:] + vals[:3]
        pal = dict(zip(chaves, vals))
    arr = np.zeros((16, 16, 4), np.uint8)
    for y, row in enumerate(_linhas(nome)):
        for x, c in enumerate(row):
            if c in pal:
                r, g, b = pal[c]
                if invertido:
                    r, g, b = 255 - r, 255 - g, 255 - b
                arr[y, x] = (r, g, b, 255)
    return Image.fromarray(arr, "RGBA")


def icone_escalado(nome, px, **kw):
    """Ícone escalado (NEAREST) para lado `px`."""
    px = max(1, int(round(px)))
    return icone(nome, **kw).resize((px, px), Image.NEAREST)


def escala_entrada(frames_desde):
    """Escala 0 -> 1.2 -> 1.0 em 6 frames."""
    seq = [0.0, 0.45, 0.9, 1.2, 1.1, 1.0]
    if frames_desde < 0:
        return 0.0
    if frames_desde < len(seq):
        return seq[frames_desde]
    return 1.0


def visivel_piscando(frames_desde):
    """Depois de entrar, pisca 2x (frames 6-17), depois fixo."""
    if frames_desde < 0:
        return False
    if 6 <= frames_desde < 18:
        return ((frames_desde - 6) // 3) % 2 == 1
    return True


def cola_icone(img, nome, cx, cy, lado, frames_desde=999, corrompido=False,
               invertido=False, tremer=0.0, rng=None):
    """Cola ícone com animação de entrada centralizado em (cx, cy)."""
    s = escala_entrada(frames_desde)
    if s <= 0 or not visivel_piscando(frames_desde):
        return
    ic = icone_escalado(nome, lado * s, corrompido=corrompido, invertido=invertido)
    dx = dy = 0
    if tremer and rng is not None:
        dx, dy = (rng.integers(-1, 2, 2) * tremer).astype(int)
    img.paste(ic, (int(cx - ic.width / 2 + dx), int(cy - ic.height / 2 + dy)), ic)
