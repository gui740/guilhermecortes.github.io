def _matriz(nome):
    linhas = [l for l in ICONES[nome].strip("\n").split("\n")]
    linhas = (linhas + ["." * 16] * 16)[:16]
    return [(l + "." * 16)[:16] for l in linhas]


@lru_cache(maxsize=512)
def _base(nome, paleta_key):
    pal = dict(paleta_key)
    arr = np.zeros((16, 16, 4), np.uint8)
    for y, linha in enumerate(_matriz(nome)):
        for x, ch in enumerate(linha):
            if ch in pal:
                arr[y, x, :3] = pal[ch]
                arr[y, x, 3] = 255
    return Image.fromarray(arr, "RGBA")


def _key(p):
    return tuple(sorted(p.items()))


def icone(nome, escala=1, paleta=None):
    """Imagem RGBA do ícone em escala inteira (NEAREST)."""
    pal = paleta or PALETAS[nome]
    base = _base(nome, _key(pal))
    s = max(1, int(round(16 * escala)))
    return base.resize((s, s), Image.NEAREST)


POP = [0.0, 0.45, 0.9, 1.2, 1.1, 1.0]


def colar_animado(img, nome, cx, cy, escala, frames_desde, corrompido=False, rng=None,
                  paleta=None, piscar_sempre=False):
    """Cola o ícone com a animação de entrada padrão (pop 0→1.2→1.0 + pisca 2x).

    Retorna False se o ícone não estiver visível neste frame.
    """
    f = int(frames_desde)
    if f < 0:
        return False
    s = POP[f] if f < len(POP) else 1.0
    if f in (6, 7, 10, 11):          # pisca 2x
        return False
    if piscar_sempre and f > 12 and (f // 9) % 2 == 1:
        return False
    if s <= 0:
        return False
    pal = paleta
    dx = dy = 0
    inverter = False
    if corrompido and rng is not None:
        r = rng.random()
        if r < 0.18:
            pal = PALETAS_CORROMPIDAS[int(rng.integers(0, len(PALETAS_CORROMPIDAS)))]
        elif r < 0.25:
            inverter = True
        dx, dy = int(rng.integers(-2, 3)), int(rng.integers(-2, 3))
    im = icone(nome, escala * s, pal)
    if inverter:
        rgb = 255 - np.asarray(im)[..., :3]
        a = np.asarray(im)[..., 3:]
        im = Image.fromarray(np.concatenate([rgb, a], axis=2).astype(np.uint8), "RGBA")
    img.paste(im, (int(cx - im.width / 2 + dx), int(cy - im.height / 2 + dy)), im)
    return True
